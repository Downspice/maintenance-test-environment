import type { WorkOrder } from "./work-orders-data"

export function generateWorkOrdersPDF(workOrders: WorkOrder[]) {
  // Create a new window for printing
  const printWindow = window.open("", "_blank")

  if (!printWindow) {
    alert("Please allow popups to generate PDF")
    return
  }

  const html = `
    <!DOCTYPE html>
    <html>
      <head>
        <title>Work Orders Report</title>
        <style>
          body {
            font-family: Arial, sans-serif;
            margin: 20px;
            color: #333;
          }
          .header {
            text-align: center;
            margin-bottom: 30px;
            border-bottom: 2px solid #333;
            padding-bottom: 10px;
          }
          .header h1 {
            margin: 0;
            color: #1a79ff;
          }
          .header p {
            margin: 5px 0 0 0;
            color: #666;
          }
          table {
            width: 100%;
            border-collapse: collapse;
            margin-bottom: 20px;
          }
          th, td {
            border: 1px solid #ddd;
            padding: 8px;
            text-align: left;
          }
          th {
            background-color: #f5f5f5;
            font-weight: bold;
          }
          .status-open {
            color: #d97706;
            font-weight: bold;
          }
          .status-closed {
            color: #059669;
            font-weight: bold;
          }
          .priority-low { color: #6b7280; }
          .priority-normal { color: #3b82f6; }
          .priority-high { color: #f59e0b; }
          .priority-urgent { color: #ef4444; }
          .progress-bar {
            width: 100px;
            height: 10px;
            background-color: #e5e7eb;
            border-radius: 5px;
            overflow: hidden;
          }
          .progress-fill {
            height: 100%;
            background-color: #3b82f6;
            transition: width 0.3s ease;
          }
          .assignees {
            font-size: 12px;
          }
          .assignee-employee {
            color: #059669;
          }
          .assignee-vendor {
            color: #7c3aed;
          }
          .footer {
            margin-top: 30px;
            text-align: center;
            font-size: 12px;
            color: #666;
            border-top: 1px solid #ddd;
            padding-top: 10px;
          }
          @media print {
            body { margin: 0; }
            .no-print { display: none; }
          }
        </style>
      </head>
      <body>
        <div class="header">
          <h1>Work Orders Report</h1>
          <p>Generated on ${new Date().toLocaleDateString()} at ${new Date().toLocaleTimeString()}</p>
          <p>Total Work Orders: ${workOrders.length}</p>
        </div>
        
        <table>
          <thead>
            <tr>
              <th>Work Order #</th>
              <th>Equipment</th>
              <th>Assignees</th>
              <th>Scheduled Date</th>
              <th>Status</th>
              <th>Progress</th>
              <th>Priority</th>
              <th>Due Date</th>
            </tr>
          </thead>
          <tbody>
            ${workOrders
              .map(
                (wo) => `
              <tr>
                <td>${wo.number}</td>
                <td>
                  <strong>${wo.equipment.name}</strong><br>
                  <small>${wo.equipment.model}</small>
                </td>
                <td class="assignees">
                  ${wo.assignees
                    .map(
                      (assignee) => `<div class="assignee-${assignee.type}">${assignee.name} (${assignee.type})</div>`,
                    )
                    .join("")}
                </td>
                <td>${new Date(wo.scheduledDate).toLocaleDateString()}</td>
                <td class="status-${wo.status}">${wo.status.toUpperCase()}</td>
                <td>
                  <div class="progress-bar">
                    <div class="progress-fill" style="width: ${(wo.progress.completed / wo.progress.total) * 100}%"></div>
                  </div>
                  ${wo.progress.completed}/${wo.progress.total} tasks
                </td>
                <td class="priority-${wo.priority}">${wo.priority.toUpperCase()}</td>
                <td>${wo.dueDate ? new Date(wo.dueDate).toLocaleDateString() : "N/A"}</td>
              </tr>
            `,
              )
              .join("")}
          </tbody>
        </table>

        <div class="footer">
          <p>This report contains ${workOrders.length} work order(s)</p>
          <p>Report generated by Work Order Management System</p>
        </div>

        <script>
          window.onload = function() {
            window.print();
            window.onafterprint = function() {
              window.close();
            };
          };
        </script>
      </body>
    </html>
  `

  printWindow.document.write(html)
  printWindow.document.close()
}
